-- Conversations and their messages. Idempotent: safe to run on every start.
-- TEMPORARY (written in CFD-06): CFD-05 owns this file and may replace or extend it.

CREATE TABLE IF NOT EXISTS conversations (
    id           uuid PRIMARY KEY,                       -- generated by the api (uuid4)
    patient_ref  text NOT NULL CHECK (btrim(patient_ref) <> ''),
    status       text NOT NULL DEFAULT 'active'
                 CHECK (status IN ('active', 'awaiting_approval', 'closed')),
    created_at   timestamptz NOT NULL                    -- from the injected Clock
);

CREATE TABLE IF NOT EXISTS messages (
    id               bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,  -- gives the message order
    conversation_id  uuid NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
    role             text NOT NULL CHECK (role IN ('patient', 'assistant')),
    text             text NOT NULL,
    intent           text,                                -- assistant messages only
    outcome          text,                                -- assistant messages only
    created_at       timestamptz NOT NULL                 -- from the injected Clock
);

CREATE INDEX IF NOT EXISTS messages_conversation_idx ON messages (conversation_id, id);
