-- Staff approvals that pause a conversation (CFD-14, CFD-15). Idempotent: safe on every start.

CREATE TABLE IF NOT EXISTS approvals (
    id               uuid PRIMARY KEY,                    -- generated by the api (uuid4)
    -- RESTRICT, not CASCADE: the audit rows must outlive any clean-up of conversations.
    conversation_id  uuid NOT NULL REFERENCES conversations (id) ON DELETE RESTRICT,
    kind             text NOT NULL CHECK (kind IN ('cancellation', 'same_day_booking')),
    booking_id       bigint NOT NULL REFERENCES bookings (id),
    status           text NOT NULL DEFAULT 'pending'
                     CHECK (status IN ('pending', 'approved', 'rejected')),
    decided_by       text,
    reason           text,
    decided_at       timestamptz,                         -- from the injected Clock
    resumed_at       timestamptz,                         -- set once the workflow has resumed
    created_at       timestamptz NOT NULL,                -- from the injected Clock
    CHECK ((status = 'pending') = (decided_at IS NULL)),
    CHECK (resumed_at IS NULL OR decided_at IS NOT NULL)
);

-- "Already waiting for approval": at most one pending approval per booking and kind.
CREATE UNIQUE INDEX IF NOT EXISTS approvals_one_pending_per_booking
    ON approvals (kind, booking_id) WHERE status = 'pending';
-- A conversation is paused at one approval at a time.
CREATE UNIQUE INDEX IF NOT EXISTS approvals_one_pending_per_conversation
    ON approvals (conversation_id) WHERE status = 'pending';
-- Startup reconcile: decided but the workflow never resumed (crash in between).
CREATE INDEX IF NOT EXISTS approvals_unresumed_idx
    ON approvals (decided_at) WHERE status <> 'pending' AND resumed_at IS NULL;

-- A database created before the reference existed gets it now. NOT VALID checks new rows only, so
-- an old row that points at no booking cannot stop the api from starting.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'approvals_booking_id_fkey' AND conrelid = 'approvals'::regclass
    ) THEN
        ALTER TABLE approvals
            ADD CONSTRAINT approvals_booking_id_fkey
            FOREIGN KEY (booking_id) REFERENCES bookings (id) NOT VALID;
    END IF;
END
$$;
